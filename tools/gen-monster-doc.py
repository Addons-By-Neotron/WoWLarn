#!/usr/bin/env python3
"""Writes MONSTERS.md: every monster with its stats, where it appears and the look it has now.
Run from the addon directory: python3 tools/gen-monster-doc.py"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = (ROOT / "Data" / "Monsters.lua").read_text()
rows = []
for m in re.finditer(r'\[(\d+)\] = \{ name = "([^"]+)", level = (-?\d+), armorclass = (-?\d+), damage = (-?\d+), '
                     r'attack = (\d+), intelligence = (\d+), gold = (\d+), hitpoints = (\d+), experience = (\d+), flags = (\d+)', data):
    i, name, lv, ac, dam, att, intel, gold, hp, xp, flags = m.groups()
    rows.append(dict(id=int(i), name=name, level=int(lv), ac=int(ac), dam=int(dam), att=int(att), intel=int(intel),
                     gold=int(gold), hp=int(hp), xp=int(xp), flags=int(flags)))

tiers = [int(x) for x in re.search(r"T\.monstlevel = \{([^}]*)\}", (ROOT / "Data" / "Tables.lua").read_text()).group(1).split(",")]

# makemonst(lev): lev 1..4 gives ids 1..tiers[lev], lev >= 5 gives tiers[lev-3]+1..tiers[lev];
# levels deeper than 12 count as 12. Id 47 (water lord) is skipped.
def appears(mid):
    levels = []
    for lev in range(1, 13):
        lo = 1 if lev < 5 else tiers[lev - 4] + 1
        hi = tiers[lev - 1]
        if lo <= mid <= hi and mid != 47:
            levels.append(lev)
    return levels

def span(levels):
    if not levels:
        return ""
    return f"{levels[0]}" if len(levels) == 1 else f"{levels[0]}-{levels[-1]}" + ("+" if levels[-1] == 12 else "")

ATTACK = {
    0: "", 1: "rusts armor", 2: "fire breath (8-22)", 3: "fire breath (26-45)", 4: "sting, -1 strength",
    5: "cold breath (19-33)", 6: "drains a level", 7: "gusher (26-40)", 8: "steals gold", 9: "disenchants an item",
    10: "barbed tail (1-25)", 11: "confuses", 12: "random special attack", 13: "psionics (31-45)",
    14: "steals an item", 15: "bite (6-15)", 16: "bite (11-25)",
}
# the names the addon uses where they differ, and the looks in Data/Visuals.lua
visuals = (ROOT / "Data" / "Visuals.lua").read_text()
renamed = dict((k, v) for k, v in re.findall(r"\[K\.([A-Z]+)\] = L\[\"([^\"]+)\"\]", visuals))
# armour classes the addon changed from the original (V.MONSTER_AC)
armor = dict((k, int(v)) for k, v in re.findall(r"\[K\.([A-Z]+)\] = (\d+),", visuals[visuals.index("V.MONSTER_AC = {"):]
                                                  .split("}")[0]))
looks = {}
block = visuals[visuals.index("V.DISPLAY = {"):visuals.index("V.MONSTER_SOUND = {")]
block = block[:block.rindex("\n}")]  # (the table ends at its closing brace)
for k, plus, v in re.findall(r"^   \[K\.([A-Z0-9]+)(?: \+ (\d+))?\] = ([^\n]+?),?(?:\s*--[^\n]*)?\n", block, re.M):
    looks[k + ("+" + plus if plus else "")] = v.strip().rstrip(",")  # (the demon lords: DEMONLORD+1, ...)
consts = (ROOT / "Core" / "Constants.lua").read_text()
const_name = {}
for k, v in re.findall(r"\n   ([A-Z0-9]+) = (\d+),", consts):
    const_name.setdefault(int(v), []).append(k)

def key_of(row):
    if row["id"] > 57 and row["id"] < 64 and f"DEMONLORD+{row['id'] - 57}" in looks:
        return f"DEMONLORD+{row['id'] - 57}"
    for k in const_name.get(row["id"], []):
        if k in looks or k in renamed:
            return k
    return None

out = ["# Monsters", "",
       "Generated by `tools/gen-monster-doc.py` from `Data/Monsters.lua`. The numbers are the original Ularn",
       "ones at difficulty 0; a higher difficulty scales hit points, damage and gold.", "",
       "- **Depth:** the dungeon levels where the monster turns up at random. `12+` means level 12 and everything deeper",
       "  (dungeon levels 13 to 15 and the volcano use the level 12 list).",
       "- **Hits:** damage is up to this number, plus the bonus of a special attack.",
       "- **AC:** armor class. Lower is harder to hit. **INT:** how smart it is (chasing range).",
       "- **Look:** the model the monster has now in the addon (a display id, or a list of them), or `-` if none yet.",
       "- Rats (the lemmings) can replace any monster on a dungeon level, about one in ten, up to a cap per level.",
       "- Demon lords are put on dungeon levels 11 to 15 (as many as the level minus 10), demon princes on the volcano",
       "  levels, Lucifer is the boss at the bottom.", ""]
def pretty(text):
    """Displays({ 6920, 6931 }) -> 6920-6931"""
    m = re.fullmatch(r"Prefer\(\{(.*?)\},\s*\{(.*?)\}\)", text)
    if m:  # first choices, and a backup for a client that lacks them
        return f"{pretty(m.group(1).strip())} (else {pretty(m.group(2).strip())})"
    m = re.fullmatch(r"Displays\((.*)\)", text)
    if not m:
        return text
    parts = re.findall(r"\{\s*(\d+),\s*(\d+)\s*\}|(-?\d+)", m.group(1))
    return ", ".join(f"{lo}-{hi}" if lo else (f"model {single[1:]}" if single.startswith("-") else single)
                     for lo, hi, single in parts)

def table(title, selected):
    out = [f"## {title}", "",
           "| # | Monster | Depth | HP | AC | Hits | INT | Special attack | Gold | XP | Look |",
           "|--:|---|---|--:|--:|--:|--:|---|--:|--:|---|"]
    for r in selected:
        k = key_of(r)
        look = pretty(looks.get(k, "-")) if k else "-"
        ac = armor.get(k, r["ac"])
        special = ATTACK.get(r["att"], str(r["att"]))
        if r["flags"] & 4:
            special = (special + "; " if special else "") + "no beheading"
        depth = span(appears(r["id"])) if r["id"] < 57 else "-"
        name = r["name"]
        if k in renamed:
            name = f"{renamed[k]} ({name})"
        out.append(f"| {r['id']} | {name} | {depth} | {r['hp']} | {ac} | {r['dam']} | {r['intel']} | "
                   f"{special} | {r['gold']} | {r['xp']} | {look} |")
    out.append("")
    return out

normal = [r for r in rows if r["id"] < 57]
first = {r["id"]: (appears(r["id"]) or [99])[0] for r in normal}
for lev in sorted(set(first.values())):
    title = f"First seen on dungeon level {lev}" if lev < 99 else "Never made at random"
    out += table(title, [r for r in normal if first[r["id"]] == lev])
out += table("Demons", [r for r in rows if r["id"] >= 57])
(ROOT / "MONSTERS.md").write_text("\n".join(out) + "\n")
print("wrote MONSTERS.md,", len(rows), "monsters")
