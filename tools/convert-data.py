#!/usr/bin/env python3
"""Generate Constants.lua and Data/*.lua from the Ularn C sources.

Usage: tools/convert-data.py [path-to-ularn]   (default /opt/workspace/ularn)

Index conventions (design.md section 5): c[] indices, scroll/potion ids and
other 0-based enums are shifted +1; object and monster ids (already 1-based)
are kept as they are.
"""
import re
import sys
from pathlib import Path

ULARN = Path(sys.argv[1] if len(sys.argv) > 1 else "/opt/workspace/ularn") / "src"
OUT = Path(__file__).resolve().parent.parent
HEADER = "-- Generated by tools/convert-data.py from the Ularn sources. Do not edit by hand.\n"


def defines(text):
    """(name, int, comment) for every simple numeric #define."""
    result = []
    for line in text.splitlines():
        m = re.match(r"#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)\s*(?:/\*\s*(.*?)\s*\*/)?", line)
        if m:
            result.append((m.group(1), int(m.group(2), 0), m.group(3) or ""))
    return result


def section(text, start, end):
    i = text.index(start)
    j = text.index(end, i) if end else len(text)
    return text[i:j]


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def constants():
    player = (ULARN / "player.h").read_text()
    itm = (ULARN / "itm.h").read_text()
    monst = (ULARN / "monst.h").read_text()
    lines = [HEADER, "local _, ns = ...\n", "ns.K = {"]

    lines.append("   -- Limits (header.h). Coordinates run 1..MAXX and 1..MAXY; levels 0..NLEVELS-1.")
    for name, value in [
        ("MAXLEVEL", 16), ("MAXVLEVEL", 5), ("NLEVELS", 21), ("DBOTTOM", 15), ("VBOTTOM", 20),
        ("MAXX", 67), ("MAXY", 17), ("MAXPLEVEL", 100), ("MAXSCROLL", 28), ("MAXPOTION", 35),
        ("MAXOBJ", 93), ("MAXMONST", 57), ("IVENSIZE", 26), ("SCORESIZE", 25), ("DNDSIZE", 92),
        ("SPNUM", 39), ("TIMELIMIT", 40000), ("TAXRATE", 0.05), ("LOGNAMESIZE", 40),
    ]:
        lines.append(f"   {name} = {value},")

    lines.append("\n   -- Character attribute indices c[] (player.h), shifted +1.")
    count = 0
    for name, value, comment in defines(player):
        lines.append(f"   {name} = {value + 1},")
        count += 1
    assert count > 90, count

    lines.append("\n   -- Object ids (itm.h). Unchanged: 0 is an empty tile.")
    objects = section(itm, "#define OALTAR", "/*** Scrolls ***/")
    for name, value, comment in defines(objects):
        lines.append(f"   {name} = {value},")

    lines.append("\n   -- Scroll ids (itm.h), shifted +1.")
    for name, value, comment in defines(section(itm, "/*** Scrolls ***/", "/*** Potions ***/")):
        lines.append(f"   {name} = {value + 1},")

    lines.append("\n   -- Potion ids (itm.h), shifted +1.")
    for name, value, comment in defines(section(itm, "/*** Potions ***/", "/*** How enchantment")):
        lines.append(f"   {name} = {value + 1},")

    lines.append("\n   -- How enchantment happened (flags, not indices).")
    for name, value, comment in defines(section(itm, "/*** How enchantment", None)):
        lines.append(f"   {name} = {value},")

    lines.append("\n   -- Monster ids and flags (monst.h). Ids unchanged: 0 is no monster.")
    for name, value, comment in defines(monst):
        lines.append(f"   {name} = {value},")
    lines.append("}\n")
    (OUT / "Constants.lua").write_text("\n".join(lines))


def tables():
    data = (ULARN / "data.c").read_text()
    out = [HEADER, "local _, ns = ...\n", "local K = ns.K\n", "local T = {}", "ns.Tables = T\n"]

    # Experience needed per level: skill[level] is the experience for level+1 (C index 0 = level 0).
    body = section(data, "long skill[]", "#undef MEG")
    body = body[body.index("{") + 1:]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    nums = [int(eval(tok.replace("MEG", "1000000"))) for tok in re.findall(r"[\d\*MEG]+", body) if tok.strip("*")]
    out.append("-- skill[level + 1] is the experience needed for the next level (C: skill[level]).")
    out.append("T.skill = {" + ", ".join(str(n) for n in nums) + "}\n")

    # Level titles. class[level - 1] in C -> T.class[level] here.
    macros = dict(re.findall(r'static char (aa\d)\[\]\s*=\s*"(.*?)";', data))
    body = section(data, "char *class[]=", "};")
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = body[body.index("{") + 1:]
    titles = []
    for tok in re.findall(r'"[^"]*"|aa\d', body):
        titles.append(tok[1:-1] if tok.startswith('"') else macros[tok])
    assert len(titles) == 102, len(titles)
    out.append("-- T.class[level] is the title for that character level (C: class[level - 1]).")
    out.append("T.class = {" + ", ".join(lua_string(t.strip()) for t in titles) + "}\n")

    # Level names: indexed by level number 0..20, so shifted +1 (levelname[level + 1]).
    body = section(data, "char *levelname[]", "};")
    names = re.findall(r'"([^"]*)"', body)
    assert len(names) == 21, len(names)
    out.append("-- T.levelname[level + 1], level 0..20.")
    out.append("T.levelname = {" + ", ".join(lua_string(n.strip()) for n in names) + "}\n")

    # Glyph strings: glyph for id is sub(id + 1, id + 1).
    for var, lua in (("monstnamelist", "monstglyphs"), ("objnamelist", "objglyphs")):
        m = re.search(var + r'\[\]=\s*"(.*?)";', data, re.S)
        out.append(f"-- {lua}:sub(id + 1, id + 1) is the original ASCII glyph.")
        out.append(f"T.{lua} = {lua_string(m.group(1))}\n")

    # Object names by id (index in the C array is the id).
    body = section(data, "char *objectname[]=", "};")
    body = body[body.index("{") + 1:]
    strings = re.findall(r'"([^"]*)"', body)
    out.append("-- T.objectname[id] for the ids that have a name.")
    out.append("T.objectname = {")
    for i, s in enumerate(strings):
        if s:
            out.append(f"   [{i}] = {lua_string(s)},")
    out.append("}\n")

    body = section(data, "char monstlevel[]", ";")
    nums = re.findall(r"\d+", body[body.index("{"):])
    out.append("-- Highest monster id that can be created, per tier (C: monstlevel[]).")
    out.append("T.monstlevel = {" + ", ".join(nums) + "}\n")
    # Scroll, potion and spell names. C index i becomes i + 1; the leading space of the
    # potion and scroll names is dropped and the unused entries are empty.
    for var, lua, count in (("scrollname", "scrollname", 28), ("potionname", "potionname", 35)):
        body = section(data, f"char *{var}[MAX", "};")
        names = [n.strip() for n in re.findall(r'"([^"]*)"', body)]
        assert len(names) == count, (var, len(names))
        out.append(f"-- T.{lua}[id]: empty for the unused ids.")
        out.append(f"T.{lua} = {{" + ", ".join(lua_string(n) for n in names) + "}\n")
    code = re.findall(r'"(\w+)"', section(data, "char *spelcode[]", "};"))
    names = re.findall(r'"([^"]*)"', re.sub(r"/\*.*?\*/", "", section(data, "char *spelname[]", "};")))
    desc = re.findall(r'"([^"]*)"', re.sub(r"/\*.*?\*/", "", section(data, "char *speldescript[]", "};")))
    assert len(code) == 39 and len(names) == 40 and len(desc) == 40, (len(code), len(names), len(desc))
    out.append("-- Spells 1..39 (C: 0..38): three letter code, name and description.")
    out.append("T.spelcode = {" + ", ".join(lua_string(n) for n in code) + "}")
    out.append("T.spelname = {" + ", ".join(lua_string(n) for n in names[:39]) + "}")
    out.append("T.speldescript = {" + ", ".join(lua_string(n) for n in desc[:39]) + "}")
    nums = re.findall(r"\d+", section(data, "char splev[]", "};")[10:])
    out.append("-- T.splev[book level + 1]: the highest spell (C index + 1) a book of that level can teach.")
    out.append("T.splev = {" + ", ".join(nums) + "}\n")
    out.append("return T")
    (OUT / "Data" / "Tables.lua").write_text("\n".join(out) + "\n")

    # Monsters.
    body = section(data, "struct monst monster[]", "};")
    flags = {"FL_NONE": 0, "FL_GENOCIDED": 1, "FL_HEAD": 2, "FL_NOBEHEAD": 4}
    rows = []
    for m in re.finditer(r'\{\s*"([^"]*)"\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,'
                         r'\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*([\w|\s]+?)\s*\}', body):
        name, level, ac, dam, att, intel, gold, hp, exp, fl = m.groups()
        flagval = 0
        for part in fl.split("|"):
            part = part.strip()
            flagval |= flags[part] if part in flags else int(part, 0)
        rows.append((name, level, ac, dam, att, intel, gold, hp, exp, flagval))
    assert rows[0][0] == "" and len(rows) == 66, len(rows)
    out = [HEADER, "local _, ns = ...\n",
           "-- monster[id] for id 1..65 (C: monster[], without the dummy entry 0).",
           "-- Pristine values: Monster.init makes the per-game copy, scaled by the difficulty (C: sethard).",
           "-- flags: 1 genocided, 2 has a head, 4 cannot be beheaded.",
           "ns.MonsterData = {"]
    for i, (name, level, ac, dam, att, intel, gold, hp, exp, flagval) in enumerate(rows):
        if i == 0:
            continue
        out.append(f"   [{i}] = {{ name = {lua_string(name)}, level = {level}, armorclass = {ac}, damage = {dam}, "
                   f"attack = {att}, intelligence = {intel}, gold = {gold}, hitpoints = {hp}, "
                   f"experience = {exp}, flags = {flagval} }},")
    out.append("}")
    (OUT / "Data" / "Monsters.lua").write_text("\n".join(out) + "\n")


def help_pages():
    # help.c: the first byte is the page count; then 23 lines for the intro and for each page.
    raw = (ULARN.parent / "data" / "Uhelp").read_text(errors="replace")
    count = int(raw[0])
    lines = raw[1:].split("\n")
    pages = []
    for i in range(count + 1):
        chunk = lines[i * 23:(i + 1) * 23]
        text = "\n".join(l.rstrip() for l in chunk).rstrip()
        text = text.replace("\x1b[7m", "|cffffd100").replace("\x1b[m", "|r")
        pages.append(text)
    out = [HEADER, "local _, ns = ...\n",
           "-- Page 1 is the story shown at the start of a game; pages 2..n are the help screens.",
           "ns.HelpPages = {"]
    for text in pages:
        out.append("   " + lua_long_string(text) + ",")
    out.append("}")
    (OUT / "Data" / "Help.lua").write_text("\n".join(out) + "\n")


def fortunes():
    lines = [l.rstrip() for l in (ULARN.parent / "data" / "Ufortune").read_text(errors="replace").split("\n")]
    lines = [l for l in lines if l]
    out = [HEADER, "local _, ns = ...\n", "-- The fortune cookie messages (C: data/Ufortune).", "ns.Fortunes = {"]
    out += ["   " + lua_string(l) + "," for l in lines]
    out.append("}")
    (OUT / "Data" / "Fortunes.lua").write_text("\n".join(out) + "\n")


def lua_long_string(text):
    # Lua 5.1 rejects a nested opening bracket of the same level as well as a closing one.
    level = 0
    while ("]" + "=" * level + "]") in text or ("[" + "=" * level + "[") in text:
        level += 1
    return "[" + "=" * level + "[\n" + text + "]" + "=" * level + "]"


def array_body(text, decl):
    """Comment-free text between the braces of a C array initialiser."""
    body = section(text, decl, ";")
    body = body[body.index("{") + 1:body.rindex("}")]
    return re.sub(r"/\*.*?\*/", "", body, flags=re.S)


def lua_list(body, ids):
    """Convert the elements of a C initialiser: names in ids come from K, numbers stay."""
    items = []
    for tok in re.findall(r"\w+", body):
        items.append(tok if tok.isdigit() else f"K.{tok}")
        assert tok.isdigit() or tok in ids, tok
    return items


def item_tables():
    data = (ULARN / "data.c").read_text()
    monster = (ULARN / "monster.c").read_text()
    constants = (OUT / "Constants.lua").read_text()
    ids = set(re.findall(r"^\s+(\w+) = ", constants, re.M))
    out = [HEADER, "local _, ns = ...\n", "local K = ns.K\n", "local I = {}", "ns.ItemTables = I\n",
           "-- Probability tables of data.c. Scroll and potion ids are the shifted (+1) ones;",
           "-- rolls index them with rund(n) + 1. Where the C rolls past the end of a table",
           "-- (scprob, potprob, nch) the entry past the end is nil here, see Create.lua.\n"]
    for var in ("scprob", "potprob"):
        items = lua_list(array_body(data, f"char {var}[]"), ids)
        out.append(f"I.{var} = {{ " + ", ".join(items) + " }")
        out.append(f"-- {len(items)} entries\n")
    for var in ("nlpts", "nch", "nplt", "ndgg", "nsw"):
        items = lua_list(array_body(data, f"char {var}[]"), ids)
        out.append(f"I.{var} = {{ " + ", ".join(items) + " }")
    # nobjtab[tmp] with tmp = rnd(n): the C array starts with a dummy 0 at index 0, kept as nobjtab[1] is
    # the first real entry here (index = C index, so nobjtab[1..37]).
    items = lua_list(array_body(monster, "static char     nobjtab[]"), ids)
    assert items[0] == "0" and len(items) == 38, len(items)
    out.append("-- nobjtab[tmp] for tmp = 1..37 (C index; the dummy entry 0 is dropped).")
    out.append("I.nobjtab = { " + ", ".join(items[1:]) + " }")
    out.append("\nreturn I")
    (OUT / "Data" / "Items.lua").write_text("\n".join(out) + "\n")


def maps():
    # Umaps: 17 rows of 67 characters per map, one blank line between maps. The C picks rund(20).
    raw = (ULARN.parent / "data" / "Umaps").read_text().split("\n")
    maps_ = []
    for i in range(0, len(raw), 18):
        rows = raw[i:i + 17]
        if len(rows) < 17:
            break
        assert all(len(r) == 67 for r in rows), (i, [len(r) for r in rows])
        maps_.append(rows)
    assert len(maps_) == 21, len(maps_)
    out = [HEADER, "local _, ns = ...\n",
           "-- ns.Maps[n][y] is row y (1..17) of canned level n: 67 characters, x = 1..67.",
           "-- # wall, D door, . monster, ~ eye of larn, ! cure dianthroritis, - random object.",
           "-- The C only ever picks maps 1..20 (rund(20)); the 21st is kept for completeness.",
           "ns.Maps = {"]
    for rows in maps_:
        out.append("   {")
        for r in rows:
            assert "]]" not in r
            out.append("      " + lua_string(r) + ",")
        out.append("   },")
    out.append("}")
    (OUT / "Data" / "Maps.lua").write_text("\n".join(out) + "\n")


constants()
tables()
help_pages()
item_tables()
maps()
fortunes()
print("ok")
