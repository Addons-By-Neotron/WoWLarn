#!/usr/bin/env python3
"""Writes Data/Anchors.lua: where the middle of what each angled picture shows is in its frame.
The rendered pictures (Media/Throne, Media/Gold, Media/Stairs, ...) are not centred in their
frame: a flat object such as the stairs down sits at the bottom of it.  The game uses the middle of the
visible part (the bounding box of the pixels that are not transparent) to put a flat object on the
middle of its tile, see V.Anchor in Data/Visuals.lua.
For a tall object that stands on a flat round base (the stairs up, the fountains) the middle of the base is used instead: it
is as wide as the picture and as high as that width times the sine of the camera angle (the
plain picture is looking straight down), on top of the bottom of the visible part.
Usage: gen-anchors.py   (run it again when the pictures are rendered again)"""
import math
import re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FOLDERS = ["Throne", "Gold", "Stairs", "Traps", "Fountain", "Elevator", "Volcano", "Buildings"]
THRESHOLD = 16  # alpha below this is not counted
ROUND_BASE = ("stairs_05_", "fountain_", "elevator_06_", "volcano_56_")  # pictures of tall things on a round base

lines = [
    "-- Generated by tools/gen-anchors.py: do not edit.",
    "-- [folder\\\\picture] = { x, y, w, h }: where the middle of the visible part of the picture is, as a part of its",
    "-- width from the left and of its height from the bottom; then how wide and high that part is, as parts of the frame.",
    "local _, ns = ...",
    "ns.Anchors = {",
]
for folder in FOLDERS:
    for path in sorted((ROOT / "Media" / folder).glob("*_icon.png")):
        alpha = Image.open(path).convert("RGBA").getchannel("A").point(lambda a: 255 if a >= THRESHOLD else 0)
        box = alpha.getbbox()
        if not box:
            continue
        width, height = alpha.size
        x = (box[0] + box[2]) / 2 / width
        y = 1 - (box[1] + box[3]) / 2 / height
        if path.name.startswith(ROUND_BASE):
            match = re.search(r"_(\d+)_icon$", path.stem)
            angle = int(match.group(1)) if match else 90
            y = 1 - box[3] / height + (box[2] - box[0]) * math.sin(math.radians(angle)) / 2 / height
        key = f"{folder}\\\\{path.stem[:-len('_icon')]}"
        lines.append(f'   ["{key}"] = {{ {x:.3f}, {y:.3f}, {(box[2] - box[0]) / width:.3f}, {(box[3] - box[1]) / height:.3f} }},')
lines.append("}")
(ROOT / "Data" / "Anchors.lua").write_text("\n".join(lines) + "\n")
print(len(lines) - 6, "pictures")
