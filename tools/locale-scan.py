#!/usr/bin/env python3
"""Add every L["..."] string used in the addon to Locales/Locale-enUS.lua (run from the addon folder).

Locale files for other languages are generated by the Babelfish script, not here."""
import glob
import re

files = [f for f in glob.glob("*.lua") + [f for d in ("Core", "Rules", "Info", "UI") for f in glob.glob(d + "/*.lua")] + glob.glob("Data/*.lua") if f != "Core/Constants.lua"]
used = []
for f in files:
    for m in re.finditer(r'\bL\["((?:[^"\\]|\\.)*)"\]', open(f).read()):
        if m.group(1) not in used:
            used.append(m.group(1))
path = "Locales/Locale-enUS.lua"
text = open(path).read()
have = set(re.findall(r'^L\["((?:[^"\\]|\\.)*)"\] = true', text, re.M))
missing = [u for u in used if u not in have]
stale = sorted(h for h in have if h not in used)
if missing:
    open(path, "w").write(text.rstrip("\n") + "\n" + "".join(f'L["{m}"] = true\n' for m in missing))
print("added", len(missing), "stale", stale)
